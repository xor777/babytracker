/*
 * Сторож зависшей связи.
 *
 * Обычная поломка сети честная: запрос отваливается с ошибкой, экран пишет
 * «сервер не отвечает» и повторяет. Но WebView телевизора умеет вставать
 * иначе: запросы не отваливаются вовсе — они просто висят. Ни ответа, ни
 * ошибки, ни таймаута. Дашборд в этот момент считает, что он «подключается»,
 * и остаётся с этой надписью навсегда: перезапуск приложения не помогает,
 * потому что сетевой стек живёт в процессе приложения, а не в странице.
 *
 * Отсюда два правила. Первое: у каждого запроса есть срок — повисший запрос
 * обязан стать ошибкой, а ошибку экран умеет показать и повторить. Второе:
 * если за несколько минут не удалось получить вообще ничего, страница
 * перезагружается целиком — это единственный доступный ей способ бросить
 * все свои сокеты и начать сеть с чистого листа.
 */

/** Сколько ждать один запрос. Больше — это уже не «медленно», а «висит». */
export const REQUEST_TIMEOUT_MS = 8_000;

/** Столько ждём открытия потока событий, прежде чем пересоздать его. */
export const STREAM_OPEN_MS = 20_000;

/** Ни одного удавшегося запроса столько времени — перезагружаем страницу. */
export const STUCK_MS = 3 * 60 * 1000;

/** Не чаще одной такой перезагрузки в этот срок: сервер бывает и правда лежит. */
export const RELOAD_COOLDOWN_MS = 10 * 60 * 1000;

export interface StuckInput {
  now: number;
  /** Когда последний раз хоть что-то пришло с сервера. */
  lastOkAt: number;
  /** Когда страница начала работать (после загрузки или перезагрузки). */
  startedAt: number;
  /** Когда сторож перезагружал страницу в прошлый раз; null — не перезагружал. */
  lastReloadAt: number | null;
}

/**
 * Пора ли перезагружать страницу.
 *
 * Условий три, и все обязательны: молчание дольше `STUCK_MS`, страница живёт
 * не меньше того же срока (иначе перезагрузка случится сразу после старта, ещё
 * до первого ответа) и с прошлой перезагрузки прошло больше `RELOAD_COOLDOWN_MS`
 * (иначе лежащий сервер превратится в бесконечный цикл перезагрузок).
 */
export function shouldReload({ now, lastOkAt, startedAt, lastReloadAt }: StuckInput): boolean {
  if (now - lastOkAt < STUCK_MS) return false;
  if (now - startedAt < STUCK_MS) return false;
  if (lastReloadAt !== null && now - lastReloadAt < RELOAD_COOLDOWN_MS) return false;
  return true;
}

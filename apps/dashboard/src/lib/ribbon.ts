/**
 * Геометрия ленты суток.
 *
 * Вынесена из компонента не ради красоты, а чтобы её можно было проверить
 * тестом. Условия просмотра у этого экрана жёсткие — телевизор, три метра,
 * боковое зрение, — и правила, которые легко нарушить случайной правкой,
 * лучше держать под присмотром:
 *
 *   • метка у самого края суток не должна вылезать за ленту;
 *   • метки не должны наезжать на подписи часов;
 *   • еда и подгузники не должны пересекаться по вертикали — их различают
 *     не цветом, а тем, по какую сторону полки они стоят;
 *   • сон остаётся самым крупным на ленте.
 */

export const RIBBON = {
  /** ширина и высота viewBox = размеру .panel__body панели 940×240 */
  W: 892,
  H: 156,

  /** дорожка сна */
  TRACK_Y: 14,
  TRACK_H: 62,

  /** полка меток: еда растёт вверх от неё, подгузники висят вниз */
  SHELF_Y: 107,
  FEED_W: 14,
  FEED_H: 26,
  DIAPER_R: 9.5,
  DIAPER_CY: 117.5,

  /**
   * Верх подписей часов: базовая линия H − 8 минус высота прописной у шрифта
   * .axis-label (22px). Ниже этой черты метки заезжать не должны.
   */
  LABEL_TOP: 132,
} as const;

/** Верхний край столбика еды. */
export const FEED_TOP = RIBBON.SHELF_Y - RIBBON.FEED_H;
/** Нижний край дорожки сна. */
export const TRACK_BOTTOM = RIBBON.TRACK_Y + RIBBON.TRACK_H;

/**
 * Центр метки, загнанный внутрь ленты.
 *
 * Метка у самого края суток иначе уезжает половиной за viewBox и выглядит
 * обрезанной — а это как раз самая свежая запись, ради которой на ленту и смотрят.
 */
export function clampCenter(cx: number, half: number): number {
  return Math.min(RIBBON.W - half, Math.max(half, cx));
}

/**
 * Моменты, попавшие в окно ленты, по возрастанию.
 * Границы включительно: событие ровно в начале суток — уже на ленте.
 */
export function marksInWindow(times: number[], from: number, to: number): number[] {
  return times.filter((ms) => ms >= from && ms <= to).sort((a, b) => a - b);
}

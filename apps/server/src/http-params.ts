/**
 * Разбор параметров пути.
 *
 * Отдельный модуль ровно по одной причине: это проверка безопасности, и две
 * её копии неизбежно разъедутся. Повод — реальный дефект: `Number.parseInt`
 * превращает «1abc», «1.5», «1e0» и «+1» в 1, поэтому `PATCH /api/events/1abc`
 * молча правил событие 1, а `DELETE /api/events/2xyz` удалял второе. Для ручек,
 * меняющих данные, приведение «почти числа» к числу недопустимо.
 */

/** Только целое положительное без знака, ведущих нулей, точек и хвостов. */
const POSITIVE_INT = /^[1-9][0-9]*$/;

/** Управляющие символы: в идентификаторе это мусор, а в логах — инъекция. */
const CONTROL_CHARS = /[\u0000-\u001F\u007F]/;

/**
 * Потолок длины. Ровно 100 — это не произвольное число: find-my-way, роутер
 * Fastify, по умолчанию не сопоставляет параметр пути длиннее 100 символов,
 * и такой запрос вообще не доходит до обработчика, падая в общий 404 по
 * `/api/*`. Держим свой предел равным ему, чтобы не обещать проверку,
 * которую наш код физически не выполняет. Для справки: uuid — 36 символов.
 */
const OPAQUE_ID_MAX = 100;

/** id строки таблицы. null — значение невалидно, вызывающий обязан ответить 400. */
export function parseRowId(raw: string | undefined): number | null {
  if (typeof raw !== 'string' || !POSITIVE_INT.test(raw)) return null;
  const value = Number(raw);
  // 2^53: за этой границей целые перестают быть различимыми
  return Number.isSafeInteger(value) ? value : null;
}

/**
 * Идентификатор набора изменений.
 *
 * Здесь проверка НАМЕРЕННО мягче, чем для числовых id, и это не недосмотр.
 * У числа есть коварное приведение типов: «1abc» становится 1 и правит чужую
 * запись. У непрозрачной строки приведения нет вообще — она уходит в запрос
 * параметром и либо находится, либо нет. Навязывать ей формат значит выдавать
 * честное «не найдено» за «неверный ввод» и отвергать идентификаторы, которые
 * когда-нибудь окажутся не uuid. Отсекаем только то, что идентификатором быть
 * не может: пустое, слишком длинное и управляющие символы.
 */
export function parseOpaqueId(raw: string | undefined): string | null {
  if (typeof raw !== 'string') return null;
  const value = raw.trim();
  if (value.length === 0 || value.length > OPAQUE_ID_MAX) return null;
  if (CONTROL_CHARS.test(value)) return null;
  return value;
}


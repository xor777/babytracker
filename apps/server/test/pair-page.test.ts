test('Chromecast опознаётся телевизором, а не телефоном', () => {
  /*
   * Цена ошибки не косметическая: у `tv` сессия бессрочная, у `phone` —
   * скользящие 90 дней (§11.5). Приставка, записанная телефоном, однажды
   * утром показала бы код сопряжения вместо дневника.
   */
  const ua =
    'Mozilla/5.0 (Linux; Android 14; Chromecast Build/UTTC.250917.004; wv) ' +
    'AppleWebKit/537.36 (KHTML, like Gecko) Version/4.0 Chrome/140.0.0.0 Safari/537.36';
  assert.equal(describeUserAgent(ua), 'Телевизор');
});

test('прочие устройства опознаются по-прежнему', () => {
  assert.equal(describeUserAgent('Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X)'), 'iPhone');
  assert.equal(describeUserAgent('Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)'), 'Компьютер Mac');
  assert.equal(describeUserAgent('Mozilla/5.0 (Linux; Android 14; Pixel 8)'), 'Телефон Android');
  assert.equal(describeUserAgent(undefined), null);
});

/**
 * §11.7: страница сопряжения.
 *
 * Тесты здесь необычные — они читают текст страницы, а не гоняют её в
 * браузере. Причина в том, что именно эта страница однажды подвела молча.
 *
 * На боевой приставке (`Chromecast Build/UTTC…; wv`) страница завела код,
 * человек одобрил его за 39 секунд — и телевизор за сессией не пришёл.
 * В базе у заявки осталось `last_polled_at = NULL`: опроса не было НИ ОДНОГО,
 * хотя обратный отсчёт на экране честно дотикал все десять минут. То есть
 * `setInterval` на этом устройстве отработал шестьсот раз подряд, а
 * `setTimeout(poll, 5000)` не привёл к отправке запроса ни разу.
 *
 * Причина осталась неустановленной, и лечение выбрано соответствующее: не
 * полагаться ни на один механизм в одиночку. Тесты закрепляют именно это —
 * свойства, потеря которых снова оставит телевизор за дверью, причём тихо.
 */

import test from 'node:test';
import assert from 'node:assert/strict';

import { makeTestApp } from './helpers.ts';
import { PAIR_PAGE_HTML } from '../src/pair-page.ts';
import { describeUserAgent } from '../src/auth-routes.ts';

/** Скрипт страницы без разметки — чтобы искать код, а не текст на экране. */
const SCRIPT = PAIR_PAGE_HTML.slice(
  PAIR_PAGE_HTML.indexOf('<script>'),
  PAIR_PAGE_HTML.lastIndexOf('</script>'),
);

/* ------------------------------------------------------------------ */
/* Самодостаточность (§11.7: открыт ровно один путь)                   */
/* ------------------------------------------------------------------ */

test('страница не тянет ни одного внешнего ресурса', () => {
  // Каждый src/href наружу пришлось бы открывать в двери отдельным путём.
  const refs = PAIR_PAGE_HTML.match(/\b(?:src|href)\s*=\s*"([^"]*)"/g) ?? [];
  assert.deepEqual(refs, [], `страница ссылается наружу: ${refs.join(', ')}`);
  assert.ok(!/<link\b/i.test(PAIR_PAGE_HTML), 'внешние стили запрещены');
});

test('страница отдаётся по /pair без сессии и не кешируется', async () => {
  const t = await makeTestApp();

  // Именно без сессии: телевизор приходит сюда, ещё не будучи никем.
  const res = await t.anon({ method: 'GET', url: '/pair' });
  assert.equal(res.statusCode, 200);
  assert.match(res.headers['content-type'] as string, /text\/html/);
  // Закешированная страница сопряжения — это застрявший код, который уже
  // никогда не сработает.
  assert.equal(res.headers['cache-control'], 'no-store');
  assert.ok(res.body.includes('Подключение устройства'));

  await t.close();
});

/* ------------------------------------------------------------------ */
/* Опрос не должен зависеть от одного механизма                        */
/* ------------------------------------------------------------------ */

test('опрос не висит на цепочке setTimeout', () => {
  /*
   * Ровно та конструкция, что подвела на телевизоре: следующий опрос
   * назначается отложенным вызовом, и стоит одному не случиться — не
   * случится больше ничего и никогда.
   */
  assert.ok(
    !/setTimeout\s*\(\s*poll\b/.test(SCRIPT),
    'опрос снова назначается через setTimeout — на боевой приставке так он не пошёл ни разу',
  );
  assert.ok(
    !/setTimeout\s*\(\s*requestCode\b/.test(SCRIPT),
    'новый код снова берётся через setTimeout',
  );
});

test('решения принимаются по часам, а не по числу сработавших таймеров', () => {
  for (const clockField of ['nextPollAt', 'nextCodeAt', 'expiresAt']) {
    assert.ok(SCRIPT.includes(clockField), `потеряна сверка по часам: ${clockField}`);
  }
  assert.ok(/now\s*>=\s*st\.nextPollAt/.test(SCRIPT), 'опрос больше не сверяется с часами');
});

test('у пульса несколько независимых источников', () => {
  // Хватит любого одного: секундного тика, кадра отрисовки, события анимации
  // или возвращения к экрану.
  assert.ok(/setInterval\s*\(\s*pump/.test(SCRIPT), 'потерян секундный тик');
  assert.ok(SCRIPT.includes('requestAnimationFrame'), 'потерян запасной пульс по кадрам');
  assert.ok(SCRIPT.includes('animationiteration'), 'потерян пульс от события анимации');
  for (const event of ['visibilitychange', 'pageshow', 'online', 'resume']) {
    assert.ok(SCRIPT.includes(event), `потеряно пробуждение по событию ${event}`);
  }
});

test('первый опрос уходит сразу, а не через интервал', () => {
  // Единственная цепочка, которая на боевой приставке доказанно работала, —
  // это ответ на запрос кода. Первый опрос обязан идти прямо из неё.
  assert.ok(
    /st\.nextPollAt\s*=\s*0;/.test(SCRIPT),
    'первый опрос снова откладывается на потом',
  );
});

test('зависший запрос не останавливает сопряжение навсегда', () => {
  assert.ok(SCRIPT.includes('REQUEST_TIMEOUT_MS'), 'нет срока ожидания ответа');
  assert.ok(SCRIPT.includes('dropBusy'), 'нет отбрасывания зависшей попытки');
});

test('есть запасной транспорт на случай, если fetch не доносит POST', () => {
  assert.ok(SCRIPT.includes('XMLHttpRequest'), 'потерян запасной транспорт');
  assert.ok(SCRIPT.includes('maybeSwitchTransport'), 'потеряно переключение транспорта');
});

/* ------------------------------------------------------------------ */
/* Перезагрузка как запасная дорога                                    */
/* ------------------------------------------------------------------ */

test('код переживает перезагрузку страницы', () => {
  /*
   * На телевизоре перезагрузка (MENU на пульте) доходила до сервера всегда,
   * а опрос — ни разу. Значит перезагрузка обязана заменять опрос: код
   * сохраняется, при старте страница сразу спрашивает, не одобрен ли он.
   */
  assert.ok(SCRIPT.includes('localStorage'), 'нет основной памяти между перезагрузками');
  assert.ok(SCRIPT.includes('document.cookie'), 'нет запасной памяти на случай запрета DOM storage');
  assert.ok(SCRIPT.includes('function recall'), 'код больше не восстанавливается после перезагрузки');
  assert.ok(SCRIPT.includes('function remember'), 'код больше не сохраняется');
});

test('сохранённый код стирается, когда он больше не нужен', () => {
  // Секрет не должен лежать дольше собственной пользы.
  const forgets = SCRIPT.match(/forget\(\)/g) ?? [];
  assert.ok(forgets.length >= 3, 'память о коде стирается слишком редко');
});

test('чужой next не подхватывается из памяти', () => {
  // Иначе сессия ушла бы не туда, куда шёл человек.
  assert.ok(/saved\.n\s*!==\s*next/.test(SCRIPT), 'потеряна сверка next при восстановлении');
});

test('на экране есть подсказка про пульт', () => {
  assert.ok(PAIR_PAGE_HTML.includes('MENU'), 'потеряна подсказка про кнопку пульта');
  assert.ok(PAIR_PAGE_HTML.includes('Назад'), 'потеряна подсказка про долгое «Назад»');
});

/* ------------------------------------------------------------------ */
/* Экран обязан быть правдивым                                         */
/* ------------------------------------------------------------------ */

test('отсчёт и состояние — разные элементы', () => {
  /*
   * Пока они делили один элемент, tick() раз в секунду затирал сообщение об
   * ошибке: «Нет связи с сервером» жило меньше секунды, и человек его не
   * видел. Ошибка была, а на экране её не было.
   */
  assert.ok(PAIR_PAGE_HTML.includes('id="clock"'), 'нет отдельной строки отсчёта');
  assert.ok(PAIR_PAGE_HTML.includes('id="note"'), 'нет отдельной строки состояния');
  assert.ok(
    !/function say\([^)]*\)\s*{[^}]*clockEl/.test(SCRIPT),
    'состояние снова пишется в строку отсчёта',
  );
});

test('истёкший код выглядит истёкшим', () => {
  // Раньше отсчёт замирал на «0:01» и мёртвый код выглядел живым.
  assert.ok(SCRIPT.includes('Срок кода истёк'), 'истечение больше не показывается');
  assert.ok(/data-state",\s*"dead"/.test(SCRIPT), 'мёртвый код не гасится');
  assert.ok(PAIR_PAGE_HTML.includes('.code[data-state="dead"]'), 'нет стиля погасшего кода');
});

test('на экране постоянно видно, что с опросом', () => {
  // У телевизора нет ни консоли, ни adb: строка диагностики — единственный
  // способ узнать, доходит ли опрос до сервера.
  assert.ok(PAIR_PAGE_HTML.includes('id="diag"'), 'потеряна строка диагностики');
  assert.ok(SCRIPT.includes('function renderDiag'), 'диагностика больше не обновляется');
  assert.ok(SCRIPT.includes('опросов '), 'не видно числа попыток опроса');
  assert.ok(SCRIPT.includes('ответов '), 'не видно числа ответов сервера');
});

test('необработанные ошибки попадают на экран', () => {
  assert.ok(/addEventListener\("error"/.test(SCRIPT), 'ошибки JS снова теряются молча');
  assert.ok(SCRIPT.includes('unhandledrejection'), 'отклонённые промисы снова теряются молча');
});

test('разметка не собирается из строк', () => {
  // Единственный сток разметки на странице входа: innerHTML здесь означал бы
  // XSS ровно там, где человек вводит код.
  // Ищем именно присваивание, а не слово: в комментарии оно объясняет запрет.
  assert.ok(!/\.innerHTML/.test(SCRIPT), 'на странице входа появился innerHTML');
});


/**
 * Цветик-семицветик — знак приложения.
 *
 * Единственное место во всём интерфейсе, где цветов больше одного.
 * Он ничего не кодирует и ничего не значит: приложение чёрно-белое, а
 * цвет в нём работает только внутри графиков и называет там тип записи.
 * Цветок — исключение ровно потому, что он не данные.
 *
 * Та же геометрия и те же семь тонов лежат в tools/make-icons.mjs, откуда
 * берётся иконка на домашнем экране: на телефоне приложение опознают по
 * ней, и расхождение читалось бы как другое приложение.
 */
const PETALS = [
  '#f5c400', // жёлтый
  '#e8402a', // красный
  '#2f6fd0', // синий
  '#2f9e5b', // зелёный
  '#f2820c', // оранжевый
  '#8a4fc4', // фиолетовый
  '#49bde0', // голубой
];

export function Flower({ className = 'brand__flower' }: { className?: string }) {
  return (
    <svg className={className} viewBox="0 0 24 24" aria-hidden="true" focusable="false">
      {PETALS.map((fill, i) => (
        <ellipse
          key={fill}
          cx="12"
          cy="5.4"
          rx="3.1"
          ry="5"
          fill={fill}
          transform={i === 0 ? undefined : `rotate(${(i * 360) / PETALS.length} 12 12)`}
        />
      ))}
      {/* Лепестки сходятся в центре, и без сердцевины там каша. */}
      <circle cx="12" cy="12" r="2.6" fill="#fff" />
    </svg>
  );
}

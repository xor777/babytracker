/**
 * Короткий код сопряжения на стороне того, кто его НАБИРАЕТ (§11.3).
 *
 * Правила здесь не «свои», а повторяют серверные из RFC 8628 §6.1 — и это
 * не дублирование ради удобства. Нормализация на клиенте нужна затем, чтобы
 * кнопка «Одобрить» включалась ровно тогда, когда сервер согласится код
 * принять: иначе человек видит набранные восемь букв, жмёт — и получает
 * отказ, потому что где-то затесался пробел. Хуже того, неудачная попытка
 * тратила бы одну из пяти.
 *
 * Сервер этим правилам не доверяет и нормализует сам (apps/server/src/
 * device-auth.ts). Здесь — только подсказка глазам и пальцам.
 */

/** RFC 8628 §6.1: A–Z без гласных. Ровно 20 символов. */
export const USER_CODE_ALPHABET = 'BCDFGHJKLMNPQRSTVWXZ';

export const USER_CODE_LENGTH = 8;

/** Где стоит тире при показе: `WDJB-MJHT`. */
const GROUP = 4;

/**
 * Привести набранное к тому виду, в каком код лежит в базе.
 *
 * Выбрасывается всё, чего в алфавите нет, — включая тире, которое сервер сам
 * же и подставил при показе. Это важнее, чем кажется: код читают с экрана
 * телевизора и набирают как видят, вместе с тире, а на телефоне к нему легко
 * прилипает пробел от автодополнения.
 *
 * Гласных в алфавите нет, поэтому набранная по ошибке `O` или `I` не станет
 * молча другим символом — она просто отбросится, и человек увидит, что букв
 * не хватает.
 */
export function normalizeUserCode(raw: string): string {
  let out = '';
  for (const ch of raw.toUpperCase()) {
    if (USER_CODE_ALPHABET.includes(ch)) out += ch;
  }
  return out.slice(0, USER_CODE_LENGTH);
}

/**
 * Показать набранное так же, как оно написано на экране устройства.
 *
 * Тире появляется само по мере набора: пока символов четыре или меньше, его
 * нет. Сверять с экраном половину кода без разделителя неудобно, а дописывать
 * тире руками человек не должен — его всё равно выбросит нормализация.
 */
export function formatUserCode(normalized: string): string {
  if (normalized.length <= GROUP) return normalized;
  return `${normalized.slice(0, GROUP)}-${normalized.slice(GROUP)}`;
}

/** Код набран целиком — только тогда есть что отправлять. */
export function isCompleteUserCode(normalized: string): boolean {
  return normalized.length === USER_CODE_LENGTH;
}

/**
 * Сколько символов осталось набрать. Нужно подписи под полем: молчаливо
 * неактивная кнопка не объясняет, чего от человека ждут.
 */
export function charsLeft(normalized: string): number {
  return Math.max(0, USER_CODE_LENGTH - normalized.length);
}

/**
 * Подтипы таксономии (§10.2) — ЕДИНСТВЕННЫЙ список на весь репозиторий.
 *
 * Зачем файл вообще есть. Список подтипов лежал в трёх местах сразу:
 * `apps/server/src/taxonomy.ts` (валидация и промпт), `apps/admin/src/lib/taxonomy.ts`
 * (подписи в админке), `apps/dashboard/src/lib/day.ts` (подписи на телевизоре).
 * Копии были независимы, и цена расхождению — не «некрасиво», а событие,
 * которое сервер запишет, а экран молча перестанет показывать: подтипа нет
 * в таблице подписей — строка просто не отрисуется, и никто не заметит,
 * потому что ошибки не будет.
 *
 * ПОЧЕМУ ПРОСТО ФАЙЛ, А НЕ ПАКЕТ РАБОЧЕГО ПРОСТРАНСТВА. Пакет — это
 * `package.json`, три записи в зависимостях, правка `pnpm-workspace.yaml`
 * и изменившийся лок-файл; взамен он не даёт ничего, чего не даёт этот файл:
 * репозиторий один, выкатка одна (§DEPLOY: на сервере лежит весь checkout,
 * сервер запускает `src/index.ts` напрямую), а `allowImportingTsExtensions`
 * уже включён во всех трёх `tsconfig.json`, поэтому относительный импорт
 * `.ts` и проверяется, и исполняется как есть.
 *
 * ПОЧЕМУ ЭТО НАДЁЖНЕЕ ТЕСТА. В CI (`.github/workflows/deploy.yml`) гоняются
 * тесты ТОЛЬКО сервера, а типы — у всех трёх приложений. Тест-сторож,
 * сверяющий три файла, пришлось бы класть в серверную папку и читать чужие
 * исходники регулярками; здесь же расхождение невозможно построить: список
 * один, а обязанность иметь подпись на каждый подтип выражена типом
 * (`SubtypeOf<T>` в ключах таблиц подписей). Забыли подпись — падает
 * `pnpm typecheck`, то есть и CI, и локальная проверка.
 *
 * Что сюда НЕ переезжает: подписи, иконки, цвета, единицы, подсказки промпту.
 * Они у каждого приложения свои по делу — на телевизоре «мокрый», в админке
 * «мокрый» с иконкой и тоном, в промпте единицы измерения, — и сводить их
 * в одно место значило бы тащить в сервер знание про цвета, а в телевизор
 * про валидацию. Общее здесь ровно одно: КАКИЕ подтипы существуют.
 */

/**
 * Тип → его подтипы, в порядке показа.
 *
 * Пустой список означает одно из двух: подтип свободный (`meds` — название
 * препарата текстом) или не нужен вовсе (`pump`, `note`). Это различие живёт
 * в `TAXONOMY` сервера (`freeSubtype`), потому что оно про валидацию, а не
 * про состав списка.
 */
export const SUBTYPES = {
  sleep: ['night', 'nap'],
  feed: ['breast', 'bottle', 'solid'],
  pump: [],
  diaper: ['wet', 'dirty', 'both'],
  measure: ['weight', 'height', 'head', 'temp'],
  meds: [],
  symptom: ['spit_up', 'vomit', 'rash', 'colic', 'crying', 'fever', 'skin_yellow', 'eyes_yellow'],
  activity: ['bath', 'walk', 'tummy_time'],
  note: [],
} as const;

/** Тип события (§10.2). Источник правды для `EventType` во всех приложениях. */
export type TypeId = keyof typeof SUBTYPES;

/** Подтипы конкретного типа как union: `SubtypeOf<'diaper'>` = 'wet' | 'dirty' | 'both'. */
export type SubtypeOf<T extends TypeId> = (typeof SUBTYPES)[T][number];

/** Типы в порядке объявления — им же идут разделы в промпте и фильтры в админке. */
export const TYPE_IDS = Object.keys(SUBTYPES) as TypeId[];

/**
 * Подтипы, которые ДЕРЖАТСЯ, а не случаются в момент.
 *
 * Симптом обычно точка: срыгнул, вырвало, заплакал. Но сыпь и желтизна
 * держатся днями, и врач спрашивает про них ровно одно: с какого дня и прошло
 * ли. Точками этого не записать — выйдет рассыпанный по ленте пунктир,
 * из которого «с 5-го по 9-й день» уже не собрать: между двумя упоминаниями
 * не отличить «держалось» от «прошло и вернулось».
 *
 * Механика у них сна: `started_at` — когда заметили, `ended_at = NULL` —
 * держится до сих пор, `ended_at` — когда сошло.
 *
 * ПРАВО БЫТЬ ДЛЯЩИМСЯ ВЫДАНО ПАРОЙ (тип, подтип), А НЕ ЦЕЛЫМ ТИПОМ. Это не
 * педантизм: длящийся `symptom` целиком означал бы, что открытыми могут висеть
 * колики и плач, у которых нет ни закрывающей фразы, ни предела правдоподобия.
 * Такое событие провисит вечно и на экране превратится в «плачет девятый час».
 *
 * Список закрыт намеренно и прирастать легко не должен. Каждый длящийся подтип
 * — это ещё одна запись, которую кто-то должен закрыть словами, а забывают
 * закрывать всё. Здесь только то, про что врач спрашивает протяжённостью:
 *
 *   - `rash` — сыпь держится днями, вопрос тот же, что про желтизну;
 *   - `skin_yellow`, `eyes_yellow` — желтизна кожи и белков глаз.
 *
 * Сознательно НЕ здесь: `spit_up` и `vomit` (точки, врач считает частоту),
 * `colic` и `crying` (закрывающей фразы не существует), `fever` (жар меряют
 * числом, а числа живут в `measure/temp` — см. §10.2 про градусы).
 *
 * ЭТО НАБЛЮДЕНИЯ, А НЕ ДИАГНОЗЫ. Родитель видит цвет и сыпь, а не болезнь.
 * Отсюда имена: `skin_yellow`, а не `jaundice`; `rash`, а не `allergy`.
 */
export const STATE_SUBTYPES = {
  symptom: ['rash', 'skin_yellow', 'eyes_yellow'],
} as const satisfies { [T in TypeId]?: readonly SubtypeOf<T>[] };

/**
 * Пары «тип/подтип», в которых могут лежать НАЗВАННЫЕ ГРАДУСЫ.
 *
 * Их две, и это не оплошность, а история. Таксономия разрешает единицу `c`
 * и у `measure/temp`, и у `symptom/fever`, так что модель имела два законных
 * места для одного числа — а сводка читала только первое. Записанный жар
 * не доезжал до врача вовсе.
 *
 * Договорённость теперь одна: ГРАДУСЫ ПИШУТСЯ В `measure/temp`, а
 * `symptom/fever` остаётся жаром без числа («горячий», «температурит»).
 * Про неё сказано модели в подсказке таксономии.
 *
 * Но ЧИТАТЬ надо оба места, и всегда. В базе уже лежат записи обоих видов,
 * физического удаления в `events` нет (§9), и переписывать настоящие данные
 * ради единообразия мы не будем: запись верна, неверен был запрос. Плюс
 * договорённость исполняет модель, а она не детерминирована — читатель,
 * знающий одно место, рано или поздно снова потеряет число.
 */
export const TEMPERATURE_SUBTYPES = [
  { type: 'measure', subtype: 'temp' },
  { type: 'symptom', subtype: 'fever' },
] as const satisfies ReadonlyArray<{ [T in TypeId]: { type: T; subtype: SubtypeOf<T> } }[TypeId]>;

/**
 * Событие с НАЗВАННЫМИ градусами — из любого из двух мест.
 *
 * Единица принимается `c` или пустая: `c` — единственная осмысленная для обоих
 * подтипов, а число без единицы у температуры это градусы. По правдоподобию
 * ничего не отсеивается: сводка показывает факты, а не их оценку.
 */
export function isTemperatureReading(e: {
  type: string;
  // `undefined` наравне с `null`: админка читает ответ сервера терпимо
  // (§«лишние поля не мешают, отсутствующие не роняют экран»), и поле может
  // просто не приехать. Для нас это одно и то же — значения нет.
  subtype?: string | null;
  value_num?: number | null;
  value_unit?: string | null;
}): boolean {
  if (e.value_num === null || e.value_num === undefined) return false;
  if (e.value_unit !== 'c' && e.value_unit !== null && e.value_unit !== undefined) return false;
  return TEMPERATURE_SUBTYPES.some((t) => t.type === e.type && t.subtype === e.subtype);
}

/** Подтип-состояние: у него осмысленны `ended_at = NULL` и протяжённость. */
export function isStateSubtype(type: string, subtype: string | null | undefined): boolean {
  if (subtype === null || subtype === undefined || subtype === '') return false;
  const known: Readonly<Record<string, readonly string[]>> = STATE_SUBTYPES;
  return (known[type] ?? []).includes(subtype);
}

/** Пары «тип/подтип», которые являются состояниями. Порядок — как в `SUBTYPES`. */
export function stateSubtypePairs(): Array<{ type: TypeId; subtype: string }> {
  const known: Readonly<Record<string, readonly string[]>> = STATE_SUBTYPES;
  const out: Array<{ type: TypeId; subtype: string }> = [];
  for (const type of TYPE_IDS) {
    for (const subtype of SUBTYPES[type] as readonly string[]) {
      if ((known[type] ?? []).includes(subtype)) out.push({ type, subtype });
    }
  }
  return out;
}
